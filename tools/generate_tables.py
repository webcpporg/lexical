"""Writes the Unicode tables of lexical's regular expressions from the pinned Unicode files.

Usage: generate_tables.py [--cache DIR] [TABLES]

The inputs are the files tools/unicode.json pins, each by its URL and its SHA-256. A file missing
from the cache directory (default: bin/unicode/<version>/ of the superproject, which idna's
generator fills too) is downloaded into it; every file is hashed, and a digest that differs from
the pinned one stops the generator, naming the file (or the URL it was downloaded from, which then
leaves nothing in the cache) and both digests, before anything is written.

The one output is written at the path given, or by default at its place in the library:
include/webcpp/lexical/detail/regex_tables.hpp, what the syntax of an ECMA-262 pattern in u mode
reads of Unicode, as constexpr arrays: every name and alias \\p{...} accepts, of a value of
General_Category, of one of the 53 binary properties ECMA-262 lists, and of a script; and the
ranges of ID_Start and ID_Continue, which a group's name is made of. A script that no code point
has, as Script or among its Script_Extensions, has no name, as ECMA-262's table of the values of
Script leaves it out (Katakana_Or_Hiragana, in Unicode 17.0.0). Unknown, the value of the
unassigned code points, which Scripts.txt does not list, is named although no file names it.
webcpp.generated runs it with a path in its build directory and compares the output with the
committed file, or copies it over the committed file for update-generated. Two runs write the same
bytes: no date, sorted data, "\\n" line endings. Nothing is written unless every check passed.

Before writing, the generator checks what the library assumes of the data, and stops naming the
assumption that fails: each of ECMA-262's binary properties but ASCII, Any and Assigned is a
property of PropertyAliases.txt; every script a file names is one PropertyValueAliases.txt names;
every name is ASCII and names one value of its kind; and ID_Start and ID_Continue hold code points.

Exit 0 when the output was written, 1 naming a fault, 2 on a usage error.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import textwrap
import urllib.request
from collections.abc import Iterator, Sequence
from pathlib import Path

LIBRARY = Path(__file__).resolve().parent.parent
SUPERPROJECT = LIBRARY.parent.parent
PINNED = LIBRARY / 'tools' / 'unicode.json'

TABLES = 'include/webcpp/lexical/detail/regex_tables.hpp'

CODE_POINT_BITS = 21
CODE_POINTS = 0x110000

# ECMA-262's table "Binary Unicode property aliases" (ECMAScript 2025, 22.2.2.9.2), its canonical
# names in its order; PropertyAliases.txt gives their aliases. ASCII, Any and Assigned are
# ECMA-262's own.
BINARY: tuple[str, ...] = tuple('''
    ASCII ASCII_Hex_Digit Alphabetic Any Assigned Bidi_Control Bidi_Mirrored Case_Ignorable Cased
    Changes_When_Casefolded Changes_When_Casemapped Changes_When_Lowercased
    Changes_When_NFKC_Casefolded Changes_When_Titlecased Changes_When_Uppercased Dash
    Default_Ignorable_Code_Point Deprecated Diacritic Emoji Emoji_Component Emoji_Modifier
    Emoji_Modifier_Base Emoji_Presentation Extended_Pictographic Extender Grapheme_Base
    Grapheme_Extend Hex_Digit IDS_Binary_Operator IDS_Trinary_Operator ID_Continue ID_Start
    Ideographic Join_Control Logical_Order_Exception Lowercase Math Noncharacter_Code_Point
    Pattern_Syntax Pattern_White_Space Quotation_Mark Radical Regional_Indicator Sentence_Terminal
    Soft_Dotted Terminal_Punctuation Unified_Ideograph Uppercase Variation_Selector White_Space
    XID_Continue XID_Start
'''.split())
ECMA_OWN = ('ASCII', 'Any', 'Assigned')
IDENTIFIER_PROPERTIES = ('ID_Start', 'ID_Continue')

NOTICE = """\
// Copyright (c) 2026 WebCpp.org
//
// Distributed under the Boost Software License, Version 1.0. (See
// accompanying file LICENSE_1_0.txt or copy at
// https://www.boost.org/LICENSE_1_0.txt)
//
// Generated by tools/generate_tables.py from the Unicode {version} data files: do not edit.
// Unicode License v3: its notice is in the appendix "Unicode data" of lexical's page.
"""


class Fault(Exception):
    """A reason the generator stops, said to the user."""


# Inputs


def pinned_files(pinned: Path) -> tuple[str, dict[str, dict[str, str]]]:
    """The Unicode version and each pinned file by its path in the cache."""
    data = json.loads(pinned.read_text(encoding='utf-8'))
    return data['version'], {entry['path']: entry for entry in data['files']}


def write(path: Path, data: bytes) -> None:
    """Writes the data at the path through a sibling file, so that no reader sees half of it."""
    path.parent.mkdir(parents=True, exist_ok=True)
    partial = path.with_name(path.name + '.partial')
    partial.write_bytes(data)
    partial.replace(path)


def checked(data: bytes, source: str, pinned: str) -> bytes:
    """The data, unless their SHA-256 differs from the pinned one."""
    digest = hashlib.sha256(data).hexdigest()
    if digest != pinned:
        raise Fault(f'{source}: SHA-256 {digest}, but tools/unicode.json pins {pinned}')
    return data


def fetch(entry: dict[str, str], cache: Path) -> str:
    """The text of one pinned file, downloaded into the cache when missing, its digest checked.

    A download is checked before it is kept, so that a moved URL, which may answer with another
    page, leaves nothing in the cache."""
    path = cache / entry['path']
    if path.is_file():
        return checked(path.read_bytes(), str(path), entry['sha256']).decode('utf-8')
    with urllib.request.urlopen(entry['url'], timeout=60) as response:
        body = checked(response.read(), entry['url'], entry['sha256'])
    write(path, body)
    return body.decode('utf-8')


def read_inputs(cache: Path | None) -> tuple[str, dict[str, str]]:
    """The Unicode version, and the text of every pinned file."""
    version, pinned = pinned_files(PINNED)
    cache = cache or SUPERPROJECT / 'bin' / 'unicode' / version
    return version, {path: fetch(entry, cache) for path, entry in sorted(pinned.items())}


def records(text: str) -> Iterator[tuple[int, int, list[str]]]:
    """Each data line of a UCD file as its first and last code points and its other fields."""
    for line in text.splitlines():
        body = line.split('#', 1)[0].strip()
        if not body:
            continue
        fields = [field.strip() for field in body.split(';')]
        first, _, last = fields[0].partition('..')
        yield int(first, 16), int(last or first, 16), fields[1:]


def alias_lines(text: str) -> Iterator[list[str]]:
    """Each data line of PropertyAliases.txt or PropertyValueAliases.txt as its fields."""
    for line in text.splitlines():
        body = line.split('#', 1)[0].strip()
        if body:
            yield [field.strip() for field in body.split(';')]


# The data


class Unicode:
    """Every name \\p{...} accepts, by kind, and the identifier properties, read and checked."""

    def __init__(self, inputs: dict[str, str]) -> None:
        values = inputs['ucd/PropertyValueAliases.txt']
        self.categories = [fields[1:] for fields in alias_lines(values) if fields[0] == 'gc']
        self.script_names = [fields[1:] for fields in alias_lines(values) if fields[0] == 'sc']
        self.read_binary(inputs['ucd/PropertyAliases.txt'])
        self.read_scripts(inputs)
        self.identifiers: dict[str, set[int]] = {name: set() for name in IDENTIFIER_PROPERTIES}
        for first, last, fields in records(inputs['ucd/DerivedCoreProperties.txt']):
            if len(fields) == 1 and fields[0] in self.identifiers:
                self.identifiers[fields[0]].update(range(first, last + 1))
        empty = [name for name, members in self.identifiers.items() if not members]
        if empty:
            raise Fault(f'DerivedCoreProperties.txt: {empty[0]} holds no code point')
        self.check_names()

    def read_binary(self, aliases: str) -> None:
        """The binary properties ECMA-262 lists, each with its aliases."""
        self.binary_aliases: dict[str, int] = {name: index for index, name in enumerate(BINARY)}
        found: set[str] = set()
        for fields in alias_lines(aliases):
            named = [name for name in fields if name in BINARY]
            if named:
                found.add(named[0])
                for name in fields:
                    self.binary_aliases[name] = BINARY.index(named[0])
        missing = [name for name in BINARY if name not in found and name not in ECMA_OWN]
        if missing:
            raise Fault(f'PropertyAliases.txt: no property {missing[0]}, which ECMA-262 lists')

    def read_scripts(self, inputs: dict[str, str]) -> None:
        """The scripts that some code point has, as Script or among its Script_Extensions."""
        script = {alias: index for index, names in enumerate(self.script_names)
                  for alias in names}
        used: set[int] = set()
        listed = 0
        for first, last, fields in records(inputs['ucd/Scripts.txt']):
            if fields[0] not in script:
                raise Fault(f'Scripts.txt: unknown script {fields[0]!r} at {first:04X}')
            used.add(script[fields[0]])
            listed += last - first + 1
        for first, _, fields in records(inputs['ucd/ScriptExtensions.txt']):
            for name in fields[0].split():
                if name not in script:
                    raise Fault(f'ScriptExtensions.txt: unknown script {name!r} at {first:04X}')
                used.add(script[name])
        # Scripts.txt lists no unassigned code point, and each one is Unknown, the value its header
        # gives them; ECMA-262 names that value Unknown and Zzzz.
        if listed < CODE_POINTS:
            if 'Unknown' not in script:
                raise Fault('PropertyValueAliases.txt: no script Unknown, which ECMA-262 names')
            used.add(script['Unknown'])
        self.unnamed_scripts = [index for index in range(len(self.script_names))
                                if index not in used]

    def check_names(self) -> None:
        """Every name \\p{...} accepts is ASCII and names one value of its kind."""
        for kind, names in (('General_Category', [n for v in self.categories for n in set(v)]),
                            ('Script', [n for v in self.script_names for n in set(v)]),
                            ('binary', list(self.binary_aliases))):
            for name in names:
                if not name.isascii() or not name:
                    raise Fault(f'the {kind} name {name!r} is not ASCII')
            if len(names) != len(set(names)):
                duplicate = next(n for n in names if names.count(n) > 1)
                raise Fault(f'the {kind} name {duplicate!r} names two values')

    def named_scripts(self) -> list[str]:
        """The names of the scripts some code point has."""
        return [name for index, names in enumerate(self.script_names)
                if index not in self.unnamed_scripts for name in names]


# The header


def ranges(members: set[int]) -> list[tuple[int, int]]:
    """The code points as sorted ranges, each first and last."""
    found: list[list[int]] = []
    for cp in sorted(members):
        if found and found[-1][1] == cp - 1:
            found[-1][1] = cp
        else:
            found.append([cp, cp])
    return [(first, last) for first, last in found]


def rows(items: Sequence[str], indent: str = '    ', width: int = 100) -> str:
    """The items, comma-separated, as many on a line as fit the width."""
    lines: list[str] = []
    line = indent
    for item in items:
        piece = item + ','
        if len(line) + len(piece) + 1 > width and line.strip():
            lines.append(line.rstrip())
            line = indent
        line += piece + ' '
    if line.strip():
        lines.append(line.rstrip())
    return '\n'.join(lines)


def comment(brief: str, width: int = 100) -> str:
    """A Doc Comment of the brief: on one line when it fits the width, else wrapped inside."""
    if len(f'/** {brief} */') <= width:
        return f'/** {brief} */\n'
    wrapped = textwrap.fill(brief, width, initial_indent=' ', subsequent_indent=' ')
    return f'/**\n{wrapped}\n*/\n'


def array(brief: str, kind: str, name: str, items: Sequence[str]) -> str:
    """A documented `inline constexpr std::array` of the items."""
    return (comment(brief) +
            f'inline constexpr std::array<{kind}, {len(items)}> {name}{{\n'
            f'{rows(items)}\n'
            '};\n')


def names(brief: str, name: str, spelled: Sequence[str]) -> str:
    """A sorted array of names, as std::string_view."""
    return array(f'Every name of {brief}, sorted, as \\\\p{{...}} writes it.', 'std::string_view',
                 name, [f'"{n}"' for n in sorted(set(spelled))])


def packed_ranges(brief: str, name: str, members: set[int]) -> str:
    """An array of ranges, each a first code point shifted left by 21 and a last."""
    return array(f'{brief} ranges: a first code point shifted left by {CODE_POINT_BITS}, and a'
                 ' last.', 'std::uint64_t', name,
                 [f'0x{first << CODE_POINT_BITS | last:X}' for first, last in ranges(members)])


def tables_header(version: str, unicode: Unicode) -> str:
    """The text of include/webcpp/lexical/detail/regex_tables.hpp."""
    parts = [
        NOTICE.format(version=version),
        '/**\n The Unicode ' + version + ' tables of lexical\'s regular expressions: generated,'
        ' and read\n through detail/regex_unicode.hpp alone.\n*/\n',
        '#ifndef WEBCPP_LEXICAL_DETAIL_REGEX_TABLES_HPP\n'
        '#define WEBCPP_LEXICAL_DETAIL_REGEX_TABLES_HPP\n\n'
        '#include <webcpp/lexical/config.hpp>\n\n#include <array>\n#include <cstdint>\n'
        '#include <string_view>\n\nnamespace webcpp::lexical::detail::regex_tables {\n',
        f'/** The version of Unicode the tables were generated from. */\n'
        f'inline constexpr std::string_view unicode_version = "{version}";\n',
        '// The generator lays the data out, as many values a line as fit 100 columns, and states\n'
        '// each array\'s packing above it: clang-format would put one value on each line.\n'
        '// clang-format off\n',
        names('a General_Category value', 'general_category_names',
              [name for values in unicode.categories for name in values]),
        names('a binary property ECMA-262 lists', 'binary_names', list(unicode.binary_aliases)),
        names('a script that a code point has', 'script_names', unicode.named_scripts()),
        packed_ranges('ID_Start', 'id_start', unicode.identifiers['ID_Start']),
        packed_ranges('ID_Continue', 'id_continue', unicode.identifiers['ID_Continue']),
        '// clang-format on\n',
        '}  // namespace webcpp::lexical::detail::regex_tables\n\n'
        '#endif  // WEBCPP_LEXICAL_DETAIL_REGEX_TABLES_HPP\n',
    ]
    return '\n'.join(parts)


# Main


def parse_arguments(argv: list[str]) -> argparse.Namespace:
    """The command line: the cache directory, and where the output goes."""
    parser = argparse.ArgumentParser(
        description='Writes the Unicode tables of lexical\'s regular expressions.')
    parser.add_argument('--cache', type=Path, default=None,
                        help='where the pinned files are kept (default: bin/unicode/<version>)')
    parser.add_argument('outputs', type=Path, nargs='*',
                        help=f'where {TABLES} is written (default: its place in the library)')
    arguments = parser.parse_args(argv)
    if len(arguments.outputs) > 1:
        parser.error(f'give no output path, or one for {TABLES}')
    return arguments


def generate(cache: Path | None, outputs: Sequence[Path]) -> None:
    """Reads every pinned file, checks the assumptions, and writes the output, or nothing."""
    version, inputs = read_inputs(cache)
    text = tables_header(version, Unicode(inputs))
    path = outputs[0] if outputs else LIBRARY / TABLES
    write(path, text.encode('utf-8'))


def main(argv: list[str]) -> int:
    arguments = parse_arguments(argv)
    try:
        generate(arguments.cache, arguments.outputs)
    except (Fault, OSError, KeyError, ValueError) as fault:
        print(f'generate_tables.py: {fault}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
